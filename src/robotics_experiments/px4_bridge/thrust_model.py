"""Conversion from PX4/Pegasus rotor commands to vehicle forces.

The thrust model is intentionally a separate object from the MAVLink port:
domain randomization, voltage sag, and response-lag effects belong here, and
must not be entangled with the protocol layer. Swap a different model in
without touching the bridge or the port.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Sequence

import numpy as np

from .contract import ActuatorCommands

__all__ = [
    "LinearThrustModel",
    "PegasusQuadraticThrustModel",
    "RotorDynamics",
    "RotorThrustModel",
]

# Per-motor iris defaults, identical across all four rotors. These are
# library-default fallbacks only; the Hydra px4 config is the runtime source
# of truth.
_IRIS_ROTOR_CONSTANT = 8.54858e-6
_IRIS_ROLLING_MOMENT = 1e-6
_IRIS_MIN_ROTOR_VELOCITY = 0.0
_IRIS_MAX_ROTOR_VELOCITY = 1100.0


@dataclass(frozen=True)
class RotorDynamics:
    """Forces and body-frame effects generated by a rotor model.

    All vectors use the Isaac/Pegasus body-FLU convention. ``forces_n`` is
    ordered by PX4 motor index and applied at each rotor marker. The body
    vectors are applied at the vehicle body origin.

    ``rotor_omega_rad_s`` is the per-rotor angular velocity (rad/s) used to
    produce ``forces_n``, ordered by PX4 motor index like ``forces_n``. It is an
    additive, cosmetic-only output: the bridge feeds it to the visual rotor-spin
    seam and it never re-enters the physics sink or the MAVLink lockstep. Models
    that only report force set it to zeros.
    """

    forces_n: np.ndarray
    body_torque_n_m: np.ndarray
    body_drag_n: np.ndarray
    rotor_omega_rad_s: np.ndarray


class RotorThrustModel(ABC):
    """Abstract per-motor force model.

    Implementations take an :class:`ActuatorCommands` of ``num_rotors`` command
    references. The Pegasus-compatible implementation interprets them as rotor
    angular velocity references in rad/s; the legacy linear model interprets
    them as normalized force fractions.
    """

    @property
    @abstractmethod
    def num_rotors(self) -> int: ...

    @abstractmethod
    def commands_to_forces(self, commands: ActuatorCommands) -> np.ndarray: ...

    def commands_to_dynamics(
        self,
        commands: ActuatorCommands,
        *,
        linear_body_velocity_flu: np.ndarray | None = None,
    ) -> RotorDynamics:
        """Return full vehicle effects for a command vector.

        Implementations that only model thrust can rely on this default; it
        preserves the original force-only contract.
        """
        return RotorDynamics(
            forces_n=self.commands_to_forces(commands),
            body_torque_n_m=np.zeros(3, dtype=np.float64),
            body_drag_n=np.zeros(3, dtype=np.float64),
            rotor_omega_rad_s=np.zeros(self.num_rotors, dtype=np.float64),
        )


class LinearThrustModel(RotorThrustModel):
    """Trivial uniform linear model: ``force_i = clip(c_i, 0, 1) * max_force``.

    Picks no opinion about voltage, response time, or per-motor variation.
    Intended as the seed model - replace with a curve-fit/airframe-specific
    model once domain randomization is wired up.
    """

    def __init__(self, *, num_rotors: int, max_force_n: float = 8.0):
        """Initialize the model.

        Args:
            num_rotors: Number of rotors driven by this model.
            max_force_n: Force in Newtons produced at command 1.0.
        """
        self._num_rotors = int(num_rotors)
        self._max_force_n = float(max_force_n)

    @property
    def num_rotors(self) -> int:
        return self._num_rotors

    @property
    def max_force_n(self) -> float:
        return self._max_force_n

    def commands_to_forces(self, commands: ActuatorCommands) -> np.ndarray:
        c = np.clip(np.asarray(commands.controls, dtype=np.float64), 0.0, 1.0)
        if c.shape != (self._num_rotors,):
            raise ValueError(
                f"LinearThrustModel expects shape ({self._num_rotors},), got {c.shape}"
            )
        return c * self._max_force_n


class PegasusQuadraticThrustModel(RotorThrustModel):
    """Pegasus-compatible instantaneous quadratic rotor model.

    Pegasus' PX4 backend scales ``HIL_ACTUATOR_CONTROLS`` into angular
    velocity references. Its multirotor then clips those references, computes
    ``T = k * omega^2`` per rotor, adds rotor reaction torque around body Z,
    and applies linear body drag. This class mirrors that behavior without
    taking ownership of the scene.
    """

    def __init__(
        self,
        *,
        num_rotors: int = 4,
        rotor_constant: Sequence[float] = (_IRIS_ROTOR_CONSTANT,) * 4,
        rolling_moment_coefficient: Sequence[float] = (_IRIS_ROLLING_MOMENT,) * 4,
        rot_dir: Sequence[float] = (-1.0, -1.0, 1.0, 1.0),
        min_rotor_velocity: Sequence[float] = (_IRIS_MIN_ROTOR_VELOCITY,) * 4,
        max_rotor_velocity: Sequence[float] = (_IRIS_MAX_ROTOR_VELOCITY,) * 4,
        linear_drag: Sequence[float] = (0.50, 0.30, 0.0),
    ):
        self._num_rotors = int(num_rotors)
        self._rotor_constant = self._as_vector("rotor_constant", rotor_constant)
        self._rolling_moment_coefficient = self._as_vector(
            "rolling_moment_coefficient",
            rolling_moment_coefficient,
        )
        self._rot_dir = self._as_vector("rot_dir", rot_dir)
        self._min_rotor_velocity = self._as_vector("min_rotor_velocity", min_rotor_velocity)
        self._max_rotor_velocity = self._as_vector("max_rotor_velocity", max_rotor_velocity)
        drag = np.asarray(linear_drag, dtype=np.float64)
        if drag.shape != (3,):
            raise ValueError(f"linear_drag expects shape (3,), got {drag.shape}")
        self._linear_drag = drag

    @property
    def num_rotors(self) -> int:
        return self._num_rotors

    def _as_vector(self, label: str, values: Sequence[float]) -> np.ndarray:
        array = np.asarray(values, dtype=np.float64)
        if array.shape != (self._num_rotors,):
            raise ValueError(f"{label} expects shape ({self._num_rotors},), got {array.shape}")
        return array

    def _rotor_velocity(self, commands: ActuatorCommands) -> np.ndarray:
        omega_ref = np.asarray(commands.controls, dtype=np.float64)
        if omega_ref.shape != (self._num_rotors,):
            raise ValueError(
                f"PegasusQuadraticThrustModel expects shape ({self._num_rotors},), "
                f"got {omega_ref.shape}"
            )
        return np.clip(omega_ref, self._min_rotor_velocity, self._max_rotor_velocity)

    def commands_to_forces(self, commands: ActuatorCommands) -> np.ndarray:
        omega = self._rotor_velocity(commands)
        return self._rotor_constant * np.square(omega)

    def commands_to_dynamics(
        self,
        commands: ActuatorCommands,
        *,
        linear_body_velocity_flu: np.ndarray | None = None,
    ) -> RotorDynamics:
        omega = self._rotor_velocity(commands)
        omega_squared = np.square(omega)
        forces = self._rotor_constant * omega_squared
        rolling_moment = float(
            np.sum(self._rolling_moment_coefficient * omega_squared * self._rot_dir)
        )
        if linear_body_velocity_flu is None:
            drag = np.zeros(3, dtype=np.float64)
        else:
            body_vel = np.asarray(linear_body_velocity_flu, dtype=np.float64)
            if body_vel.shape != (3,):
                raise ValueError(
                    f"linear_body_velocity_flu expects shape (3,), got {body_vel.shape}"
                )
            drag = -self._linear_drag * body_vel

        return RotorDynamics(
            forces_n=forces,
            body_torque_n_m=np.array([0.0, 0.0, rolling_moment], dtype=np.float64),
            body_drag_n=drag,
            rotor_omega_rad_s=omega,
        )
